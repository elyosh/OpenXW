/* DOS94 resident material tables at 0x699870, 0x699AE0, 0x699B0B, 0x699B3B. */
void Dos94Raster_Init(Dos94Raster* r) {
	memset(r, 0, sizeof *r);
	r->backgroundColor = 0xF7;
	memcpy(r->materialColors, initialMaterials, sizeof initialMaterials);
	memcpy(r->markColorOffset, initialMarkOffsets, sizeof initialMarkOffsets);
	memcpy(r->targetMapping, targetMapping, sizeof targetMapping);
	XwRenderDosMaterials materials = { .material_count =
										   Dos94Assets_Version() == XW_GAME_VERSION_93 ? 27 : 39 };
	memcpy(materials.colors, initialMaterials, sizeof materials.colors);
	memcpy(materials.target, targetMapping, sizeof materials.target);
	memcpy(materials.offsets, initialMarkOffsets, sizeof materials.offsets);
	memcpy(materials.markings, markingDefinitions, sizeof materials.markings);
	memcpy(materials.gate, Dos94_trainingGateColors, sizeof materials.gate);
	if (materials.material_count == 27)
		memcpy(materials.target + 23, materials.gate, sizeof materials.gate);
	XwRenderDosAssets_Materials(&materials);
	if (Dos94Assets_Version() == XW_GAME_VERSION_93) {
		/* DOS93's highlight lookup reaches these four adjacent gate-color bytes. */
		memcpy(r->targetMapping + 23, Dos94_trainingGateColors, sizeof Dos94_trainingGateColors);
	}
}

/* DOS94 0x699B7B. Mode 3 reads the adjacent, mutable remap table. */
void Dos94_DRAWPOL_setmarkingcolors(uint16_t mode) {
	Dos94Raster* r = &Dos94_display->raster;
	if (Dos94Assets_Version() == XW_GAME_VERSION_93) {
		/* Supported missions use modes 0–2; use OpenTIE's default for other inputs. */
		if (mode > 2)
			mode = 0;
		memcpy(r->materialColors + 0xD0, markingDefinitions + 16 * mode, 16);
		return;
	}
	mode &= 3;
	const uint8_t* source = mode == 3 ? r->markColorOffset : markingDefinitions + 16 * mode;
	memcpy(r->materialColors + 0xD0, source, 16);
	r->markColorOffset[14] = (uint8_t)(mode ? 2 * mode - 3 : 0);
}
