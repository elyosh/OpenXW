		objectType = XwFlightTypes_ObjectType(XW_OBJ_INTERDICTOR);
#else
		objectType = XW_OBJ_INTERDICTOR;
#endif
		initialStatus = g_spawnStatus - CREATE_MISSION_VARIANT_STATUS;
