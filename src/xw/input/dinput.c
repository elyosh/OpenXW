int g_dinputAltDown = 0;

// FUNCTION: XW 0x47BE60
int DInput_Init(void) {
	DxGuid keyboardGuid = g_directInputSystemKeyboardGuid;
	DIPROPDWORD bufferSizeProperty;
	if (DirectInputCreateA(g_hInstance, DINPUT_VERSION_5, &g_directInput, NULL) != DI_OK &&
		DirectInputCreateA(g_hInstance, DINPUT_VERSION_3, &g_directInput, NULL) != DI_OK) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Create FAILED", "ERROR", XW_STARTUP_DIALOG_OK);
		return 0;
	}
	if (g_directInput->lpVtbl->CreateDevice(g_directInput, &keyboardGuid, &g_dinputKeyboardDevice, NULL) !=
		DI_OK) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Keyboard Create FAILED", "ERROR", XW_STARTUP_DIALOG_OK);
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->SetDataFormat(g_dinputKeyboardDevice, &c_dfDIKeyboard) != DI_OK) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Keyboard Format FAILED", "ERROR", XW_STARTUP_DIALOG_OK);
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->SetCooperativeLevel(g_dinputKeyboardDevice, g_flightMainWindowHandle,
															DISCL_NONEXCLUSIVE | DISCL_FOREGROUND) != DI_OK) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Keyboard SCL FAILED", "ERROR", XW_STARTUP_DIALOG_OK);
		return 0;
	}
	bufferSizeProperty.diph.dwSize = sizeof(bufferSizeProperty);
	bufferSizeProperty.diph.dwHeaderSize = sizeof(bufferSizeProperty.diph);
	bufferSizeProperty.diph.dwObj = 0;
	bufferSizeProperty.diph.dwHow = DINPUT_PROPERTY_DEVICE;
	bufferSizeProperty.dwData = DINPUT_KEYBOARD_BUFFER_SIZE;
	if (g_dinputKeyboardDevice->lpVtbl->SetProperty(g_dinputKeyboardDevice, DINPUT_DIPROP_BUFFERSIZE,
													&bufferSizeProperty.diph) < 0) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Keyboard SetBufferSize FAILED", "ERROR",
								 XW_STARTUP_DIALOG_OK);
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice) != DI_OK) {
		XwPort_ShowStartupDialog(NULL, "Direct Input Keyboard Acquire FAILED", "ERROR", XW_STARTUP_DIALOG_OK);
		return 0;
	}
	g_dinputKeyboardAcquired = 1;
	return 1;
}

// FUNCTION: XW 0x47C010
int DInput_HasKeyReady(void) {
	uint32_t eventCount;
	DIDEVICEOBJECTDATA keyEvent;
	for (;;) {
		HRESULT readStatus;
		uint8_t baseKeyCode;
		unsigned int keyDown;
		eventCount = 1;
		readStatus = g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent),
																   &keyEvent, &eventCount, DIGDD_PEEK);
		if (readStatus == DIERR_INPUTLOST) {
			if (DInput_ReacquireKeyboard() == 0)
				return 0;
#ifdef XW_MODERN
			return 0;
#else
			continue;
#endif
		}
		if (readStatus < 0 || eventCount == 0)
			return 0;
		keyDown = keyEvent.dwData & DINPUT_KEY_DOWN;
		baseKeyCode = g_dinputKeyCodeTable[(uint8_t)keyEvent.dwOfs];
		if (baseKeyCode == DINPUT_SHIFT_MARKER) {
			g_dinputShiftDown = keyDown;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent), &keyEvent,
														  &eventCount, 0);
			continue;
		}
		if (baseKeyCode == DINPUT_CTRL_MARKER) {
			g_dinputCtrlDown = keyDown;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent), &keyEvent,
														  &eventCount, 0);
			continue;
		}
		if (baseKeyCode == DINPUT_ALT_MARKER) {
			g_dinputAltDown = keyDown;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent), &keyEvent,
														  &eventCount, 0);
			continue;
		}
		if (keyDown != 0)
			return 1;
		eventCount = 1;
		g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent), &keyEvent,
													  &eventCount, 0);
	}
}

// FUNCTION: XW 0x47C130
uint8_t DInput_GetKey(void) {
	uint32_t eventCount;
	DIDEVICEOBJECTDATA keyEvent;
	DInput_UpdateKeyboardModifierState();
	for (;;) {
		HRESULT readStatus;
		uint8_t baseKeyCode;
		unsigned int keyDown;
		eventCount = 1;
		readStatus = g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice, sizeof(keyEvent),
																   &keyEvent, &eventCount, 0);
		if (readStatus == DIERR_INPUTLOST) {
			if (DInput_ReacquireKeyboard() == 0) {
				return 0;
			}
#ifdef XW_MODERN
			return 0;
#else
			continue;
#endif
		}
		if (readStatus < 0) {
			return 0;
		}
		if (eventCount == 0) {
#ifdef XW_MODERN
			return 0;
#else
			continue;
#endif
		}
		keyDown = keyEvent.dwData & DINPUT_KEY_DOWN;
		baseKeyCode = g_dinputKeyCodeTable[(uint8_t)keyEvent.dwOfs];
		if (baseKeyCode == DINPUT_SHIFT_MARKER) {
			g_dinputShiftDown = keyDown;
		} else if (baseKeyCode == DINPUT_CTRL_MARKER) {
			g_dinputCtrlDown = keyDown;
		} else if (baseKeyCode == DINPUT_ALT_MARKER) {
			g_dinputAltDown = keyDown;
		} else if (keyDown != 0) {
			break;
		}
	}
	if (g_dinputShiftDown != 0) {
		return g_dinputShiftKeyCodeTable[(uint8_t)keyEvent.dwOfs];
	}
	if (g_dinputCtrlDown != 0) {
		return g_dinputCtrlKeyCodeTable[(uint8_t)keyEvent.dwOfs];
	}
	if (g_dinputAltDown != 0) {
		return g_dinputAltKeyCodeTable[(uint8_t)keyEvent.dwOfs];
	}
	return g_dinputKeyCodeTable[(uint8_t)keyEvent.dwOfs];
}

// FUNCTION: XW 0x47C230
void DInput_UpdateKeyboardModifierState(void) {
	uint8_t keyboardState[DINPUT_KEYBOARD_STATE_SIZE];
	if (g_dinputKeyboardDevice->lpVtbl->GetDeviceState(g_dinputKeyboardDevice, sizeof(keyboardState),
													   keyboardState) == DI_OK) {
		g_dinputShiftDown =
			keyboardState[DINPUT_KEY_LEFT_SHIFT] != 0 || keyboardState[DINPUT_KEY_RIGHT_SHIFT] != 0;
		g_dinputCtrlDown =
			keyboardState[DINPUT_KEY_LEFT_CTRL] != 0 || keyboardState[DINPUT_KEY_RIGHT_CTRL] != 0;
		g_dinputAltDown = keyboardState[DINPUT_KEY_LEFT_ALT] != 0 || keyboardState[DINPUT_KEY_RIGHT_ALT] != 0;
	}
}

// FUNCTION: XW 0x47C2B0
void DInput_Shutdown(void) {
	if (g_dinputKeyboardAcquired != 0) {
		g_dinputKeyboardDevice->lpVtbl->Unacquire(g_dinputKeyboardDevice);
		g_dinputKeyboardAcquired = 0;
	}
	if (g_dinputKeyboardDevice != NULL)
		g_dinputKeyboardDevice->lpVtbl->Release(g_dinputKeyboardDevice);
	if (g_directInput != NULL)
		g_directInput->lpVtbl->Release(g_directInput);
#ifdef XW_MODERN
	g_dinputKeyboardDevice = NULL;
	g_directInput = NULL;
#endif
}

// FUNCTION: XW 0x47C2F0
int DInput_ReacquireKeyboard(void) {
#ifdef XW_MODERN
	if (!XwInput_CanReacquireKeyboard())
		return 0;
#endif
	if (g_dinputKeyboardDevice != NULL) {
#ifdef XW_MODERN
		g_dinputKeyboardAcquired = g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice) == DI_OK;
		return g_dinputKeyboardAcquired;
#else
		g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice);
		g_dinputKeyboardAcquired = 1;
		return 1;
#endif
	}
	return 0;
}
