IDirectInputA* g_directInput = NULL;

// GLOBAL: XW 0x4FC8B4
IDirectInputDeviceA* g_dinputKeyboardDevice = NULL;

// GLOBAL: XW 0x4FC8B8
int g_dinputKeyboardAcquired = 0;

// GLOBAL: XW 0x4FC8BC
int g_dinputCtrlDown = 0;

